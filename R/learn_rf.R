#' Random Forest Classification
#'
#' Trains a Random Forest classification model using a single data frame
#' containing a categorical target variable and one or more predictor
#' variables.
#'
#' The function provides a general framework for classification tasks using
#' clinical, phenotypic, molecular, or other quantitative features. Predictors
#' can be selected explicitly using \code{feature_subset}, allowing the same
#' function to be used regardless of the biological or clinical origin of the
#' data.
#'
#' The function performs complete-case filtering, stratified train/test
#' splitting, Random Forest training, test-set evaluation, feature importance
#' analysis, and optional permutation testing. Diagnostic plots can also be
#' generated automatically.
#'
#' @param data Data frame containing the target variable and predictor
#'   variables. Each row represents a sample and each column represents a
#'   variable. The data frame may contain clinical, phenotypic, molecular, or
#'   other quantitative features.
#' @param target_var Character. Name of the categorical outcome variable to be
#'   predicted. The variable is converted to a factor if necessary.
#' @param feature_subset Optional character vector specifying the predictor
#'   variables to include in the model. If \code{NULL}, all available
#'   predictor columns are used, excluding \code{target_var} and
#'   \code{sample_col}. This allows the same interface to be used for
#'   metadata-only, molecular-only, or combined datasets.
#' @param sample_col Character. Optional column containing sample identifiers
#'   (default: \code{"Sample"}). This column is excluded from the predictors.
#'   If the column is not present, a warning is issued and sample identifiers
#'   are not stored separately.
#' @param train_fraction Numeric. Proportion of samples assigned to the
#'   training set using stratified sampling (default: \code{0.7}).
#' @param ntree Integer. Number of trees to grow in the Random Forest
#'   (default: \code{500}).
#' @param seed Integer. Random seed used for reproducible data partitioning,
#'   model fitting, and permutation testing (default: \code{123}).
#' @param positive_class Optional character. Reference class used for binary
#'   ROC/AUC calculations. If \code{NULL}, the second level of the target
#'   factor is used.
#' @param permutation_test Logical. Whether to perform a permutation test by
#'   randomly shuffling the training labels and refitting the model
#'   \code{nperm} times (default: \code{FALSE}).
#' @param nperm Integer. Number of permutations to perform when
#'   \code{permutation_test = TRUE} (default: \code{1000}).
#' @param plot Logical. Whether to generate and print the combined diagnostic
#'   plots to the graphics device (default: \code{TRUE}).
#'
#' @return
#' Invisibly returns an object of class \code{learn.rf}.
#'
#' The \code{learn.rf} object contains:
#' \describe{
#'   \item{call}{The original function call.}
#'   \item{model}{The trained \code{randomForest} object.}
#'   \item{x}{The complete predictor matrix used for model fitting and
#'   evaluation.}
#'   \item{y}{The target variable after complete-case filtering.}
#'   \item{x_train, x_test}{Predictor matrices for the training and testing
#'   sets.}
#'   \item{y_train, y_test}{Target vectors for the training and testing sets.}
#'   \item{train_samples, test_samples}{Sample identifiers assigned to the
#'   training and testing sets, when \code{sample_col} is available.}
#'   \item{predictions}{Predicted class labels for the test set.}
#'   \item{probabilities}{Predicted class probabilities for the test set.}
#'   \item{confusion_matrix}{Detailed confusion matrix generated by
#'   \pkg{caret}.}
#'   \item{metrics}{List containing overall and class-wise performance
#'   metrics, including Accuracy, Kappa, Precision, Recall, Specificity, F1,
#'   and AUC when applicable.}
#'   \item{importance}{Data frame containing Random Forest variable importance
#'   scores.}
#'   \item{top_features}{The top 10 features ranked by variable importance.}
#'   \item{oob_error}{Final Out-of-Bag error rate from the fitted Random
#'   Forest.}
#'   \item{permutation}{Permutation-test results, including the null accuracy
#'   distribution and empirical p-value, when enabled.}
#'   \item{plots}{List containing the generated \pkg{ggplot2} diagnostic
#'   plots.}
#'   \item{parameters}{List containing the main analysis parameters.}
#' }
#'
#' @details
#' \strong{Data structure:}
#' The function expects a sample-by-variable data frame. The target variable
#' and all predictors must be contained in the same object. This design keeps
#' the Random Forest implementation independent of the biological origin of
#' the predictors. For example, age, sex encodings, gene expression, protein
#' abundance, or metabolite measurements can all be supplied as predictors
#' through the same interface.
#'
#' \strong{Predictor selection:}
#' If \code{feature_subset} is supplied, only the specified columns are used
#' as predictors. If it is \code{NULL}, all columns other than
#' \code{target_var} and \code{sample_col} are used. This makes it possible to
#' explicitly define different predictor sets within the same dataset.
#'
#' \strong{Missing data:}
#' Samples containing missing values in the target or selected predictors are
#' removed using complete-case filtering before the train/test split.
#' Predictors must be numeric. Categorical predictors should therefore be
#' explicitly encoded numerically before calling the function.
#'
#' \strong{Sample identifiers:}
#' If \code{sample_col} is present, its values are used to track samples
#' through the analysis and are excluded from the predictor matrix. Duplicate
#' sample identifiers are not allowed.
#'
#' \strong{Stratification:}
#' The train/test partition is performed using stratified sampling, preserving
#' the class structure of the target variable across the two sets. At least
#' two samples per class are required.
#'
#' \strong{Model evaluation:}
#' Model performance is evaluated on the held-out test set using a confusion
#' matrix, Accuracy, Kappa, and class-wise Precision, Recall, Specificity,
#' and F1 score. For binary classification problems, an ROC curve and AUC are
#' also calculated.
#'
#' \strong{Variable importance:}
#' Variable importance is obtained from the fitted Random Forest using the
#' importance measures provided by \pkg{randomForest}. The returned
#' \code{top_features} object contains the ten highest-ranked predictors.
#'
#' \strong{Permutation test:}
#' If enabled, the target labels in the training set are randomly permuted
#' \code{nperm} times and a new Random Forest is fitted for each permutation.
#' The resulting null distribution is compared with the observed test-set
#' accuracy to calculate an empirical p-value. This provides a reference for
#' the observed classification performance under randomized training labels,
#' but does not replace independent validation or cross-validation.
#'
#' \strong{Visualization:}
#' When \code{plot = TRUE}, the function generates a composite diagnostic
#' visualization using \pkg{patchwork}. Depending on the classification
#' problem, the visualization includes the confusion matrix, Out-of-Bag (OOB)
#' error convergence, variable importance, and ROC curve.
#'
#' @examples
#' \dontrun{
#'
#' # Example 1: Use clinical variables as predictors
#' rf_clinical <- learn.rf(
#'   data = clinical_data,
#'   target_var = "Disease_Status",
#'   feature_subset = c("Age", "BMI", "Sex_F")
#' )
#'
#' # Example 2: Use molecular features as predictors
#' rf_genes <- learn.rf(
#'   data = expression_data,
#'   target_var = "Disease_Status",
#'   feature_subset = paste0("Gene_", 1:100)
#' )
#'
#' # Example 3: Combine clinical and molecular predictors
#' rf_combined <- learn.rf(
#'   data = combined_data,
#'   target_var = "Treatment_Response",
#'   feature_subset = c(
#'     "Age",
#'     "BMI",
#'     paste0("Gene_", 1:50)
#'   )
#' )
#'
#' # Example 4: Run a permutation test
#' rf_permutation <- learn.rf(
#'   data = expression_data,
#'   target_var = "Disease_Status",
#'   feature_subset = paste0("Gene_", 1:100),
#'   permutation_test = TRUE,
#'   nperm = 500
#' )
#' }
#'
#' @importFrom stats predict complete.cases
#' @importFrom utils head tail
#'
#' @export

learn.rf <- function(
    data,
    target_var,
    feature_subset = NULL,
    sample_col = "Sample",
    train_fraction = 0.7,
    ntree = 500,
    seed = 123,
    positive_class = NULL,
    permutation_test = FALSE,
    nperm = 1000,
    plot = TRUE
) {

# =============================================================================
# Packages
# =============================================================================

  .check_dependencies(c(
  "randomForest",
  "pROC",
  "ggplot2",
  "patchwork",
  "caret"
))

# =============================================================================
# Helpers
# =============================================================================

`%||%` <- function(x, y) {
  if (!is.null(x)) x else y
}

safe_div <- function(num, den) {
  ifelse(den == 0, NA_real_, num / den)
}

make_stratified_split <- function(y, p = 0.7) {

  idx_train <- unlist(
    lapply(split(seq_along(y), y), function(idx) {

      n_class <- length(idx)

      if (n_class < 2) {
        stop(
          "Each class must have at least 2 samples ",
          "to allow train/test splitting."
        )
      }

      n_train <- floor(n_class * p)

      n_train <- max(
        1,
        min(n_train, n_class - 1)
      )

      sample(idx, n_train)
    })
  )

  idx_train <- sort(unique(idx_train))

  idx_test <- setdiff(
    seq_along(y),
    idx_train
  )

  list(
    train = idx_train,
    test = idx_test
  )
}

# =============================================================================
# Basic checks
# =============================================================================

if (!is.data.frame(data)) {
  stop("data must be a data.frame.")
}

data <- as.data.frame(
  data,
  stringsAsFactors = FALSE
)

if (!target_var %in% colnames(data)) {
  stop(
    "target_var '",
    target_var,
    "' was not found in data."
  )
}

if (!is.null(sample_col) &&
    !sample_col %in% colnames(data)) {

  warning(
    "sample_col '",
    sample_col,
    "' was not found in data. ",
    "No sample identifier will be used."
  )

  sample_col <- NULL
}

# =============================================================================
# Target
# =============================================================================

data <- data[
  !is.na(data[[target_var]]),
  ,
  drop = FALSE
]

if (nrow(data) < 10) {
  stop(
    "Too few samples after removing missing target values."
  )
}

y <- factor(data[[target_var]])

if (nlevels(y) < 2) {
  stop(
    "target_var must contain at least two classes."
  )
}

if (any(table(y) < 2)) {
  stop(
    "Each class must contain at least 2 samples."
  )
}

# =============================================================================
# Sample identifiers
# =============================================================================

if (!is.null(sample_col)) {

  sample_ids <- data[[sample_col]]

  if (anyDuplicated(sample_ids)) {
    stop(
      "sample_col contains duplicated sample identifiers."
    )
  }

  rownames(data) <- sample_ids

} else {

  sample_ids <- rownames(data)

  if (is.null(sample_ids)) {
    sample_ids <- as.character(seq_len(nrow(data)))
  }
}

# =============================================================================
# Predictor selection
# =============================================================================

excluded_cols <- c(
  sample_col,
  target_var
)

excluded_cols <- excluded_cols[
  !is.na(excluded_cols)
]

available_features <- setdiff(
  colnames(data),
  excluded_cols
)

if (length(available_features) == 0) {
  stop(
    "No predictor variables remain after removing ",
    "sample_col and target_var."
  )
}

if (!is.null(feature_subset)) {

  missing_features <- setdiff(
    feature_subset,
    available_features
  )

  if (length(missing_features) > 0) {
    stop(
      "These feature_subset variables were not found in data: ",
      paste(missing_features, collapse = ", ")
    )
  }

  predictor_cols <- feature_subset

} else {

  predictor_cols <- available_features
}

X <- data[
  ,
  predictor_cols,
  drop = FALSE
]

rownames(X) <- sample_ids

# =============================================================================
# Remove incomplete observations
# =============================================================================

cc <- complete.cases(X, y)

if (any(!cc)) {

  X <- X[
    cc,
    ,
    drop = FALSE
  ]

  y <- y[cc]
}

if (nrow(X) < 10) {
  stop(
    "Too few complete samples after filtering NAs."
  )
}

if (nlevels(y) < 2) {
  stop(
    "Fewer than two classes remain after filtering NAs."
  )
}

if (any(table(y) < 2)) {
  stop(
    "Each class must contain at least 2 samples ",
    "after filtering NAs."
  )
}

# =============================================================================
# Predictor validation
# =============================================================================

non_numeric <- !vapply(
  X,
  is.numeric,
  logical(1)
)

if (any(non_numeric)) {

  stop(
    "All predictor variables must be numeric. ",
    "Non-numeric variables detected: ",
    paste(
      colnames(X)[non_numeric],
      collapse = ", "
    )
  )
}

# =============================================================================
# Train / Test split
# =============================================================================

set.seed(seed)

split_idx <- make_stratified_split(
  y,
  p = train_fraction
)

train_idx <- split_idx$train
test_idx  <- split_idx$test

X_train <- X[
  train_idx,
  ,
  drop = FALSE
]

X_test <- X[
  test_idx,
  ,
  drop = FALSE
]

y_train <- y[train_idx]
y_test  <- y[test_idx]

# =============================================================================
# Train Random Forest
# =============================================================================

rf_model <- randomForest::randomForest(
  x = X_train,
  y = y_train,
  ntree = ntree,
  importance = TRUE
)

# =============================================================================
# Predictions
# =============================================================================

pred_class <- predict(
  rf_model,
  newdata = X_test,
  type = "response"
)

pred_prob <- predict(
  rf_model,
  newdata = X_test,
  type = "prob"
)

# =============================================================================
# Confusion matrix
# =============================================================================

cm <- caret::confusionMatrix(
  pred_class,
  y_test
)

# =============================================================================
# Basic metrics
# =============================================================================

accuracy <- unname(
  mean(pred_class == y_test)
)

metrics <- list(
  accuracy = accuracy,
  kappa = unname(
    cm$overall["Kappa"]
  ),
  confusion_matrix = cm
)

# =============================================================================
# Per-class metrics
# =============================================================================

cm_tab <- table(
  Predicted = pred_class,
  Observed = y_test
)

class_metrics <- lapply(
  levels(y_test),
  function(cl) {

    tp <- if (
      cl %in% rownames(cm_tab) &&
      cl %in% colnames(cm_tab)
    ) {
      cm_tab[cl, cl]
    } else {
      0
    }

    fp <- if (
      cl %in% rownames(cm_tab)
    ) {
      sum(cm_tab[cl, ]) - tp
    } else {
      0
    }

    fn <- if (
      cl %in% colnames(cm_tab)
    ) {
      sum(cm_tab[, cl]) - tp
    } else {
      0
    }

    tn <- sum(cm_tab) -
      tp -
      fp -
      fn

    precision <- safe_div(
      tp,
      tp + fp
    )

    recall <- safe_div(
      tp,
      tp + fn
    )

    specificity <- safe_div(
      tn,
      tn + fp
    )

    f1 <- safe_div(
      2 * precision * recall,
      precision + recall
    )

    data.frame(
      Class = cl,
      Precision = precision,
      Recall = recall,
      Specificity = specificity,
      F1 = f1,
      stringsAsFactors = FALSE
    )
  }
)

class_metrics <- do.call(
  rbind,
  class_metrics
)

rownames(class_metrics) <- NULL

metrics$classwise <- class_metrics

# =============================================================================
# Macro metrics
# =============================================================================

metrics$macro_precision <- mean(
  class_metrics$Precision,
  na.rm = TRUE
)

metrics$macro_recall <- mean(
  class_metrics$Recall,
  na.rm = TRUE
)

metrics$macro_f1 <- mean(
  class_metrics$F1,
  na.rm = TRUE
)

# =============================================================================
# ROC / AUC
# =============================================================================

roc_obj <- NULL
auc_val <- NA_real_

if (nlevels(y_test) == 2) {

  pos_class <- positive_class %||%
    levels(y_test)[2]

  if (!pos_class %in% levels(y_test)) {
    stop(
      "positive_class '",
      pos_class,
      "' is not one of the target classes."
    )
  }

  if (!pos_class %in% colnames(pred_prob)) {
    stop(
      "positive_class '",
      pos_class,
      "' was not found among probability columns."
    )
  }

  roc_obj <- pROC::roc(
    response = y_test,
    predictor = pred_prob[, pos_class],
    levels = levels(y_test),
    quiet = TRUE
  )

  auc_val <- as.numeric(
    pROC::auc(roc_obj)
  )

  metrics$auc <- auc_val
  metrics$roc <- roc_obj
  metrics$positive_class <- pos_class
}

# =============================================================================
# Feature importance
# =============================================================================

imp <- randomForest::importance(
  rf_model
)

imp_df <- data.frame(
  Feature = rownames(imp),
  imp,
  check.names = FALSE,
  row.names = NULL
)

importance_col <- if (
  "MeanDecreaseAccuracy" %in% colnames(imp_df)
) {
  "MeanDecreaseAccuracy"
} else {
  colnames(imp_df)[2]
}

imp_df <- imp_df[
  order(
    -imp_df[[importance_col]]
  ),
  ,
  drop = FALSE
]

top_features <- utils::head(
  imp_df,
  10
)

# =============================================================================
# OOB error
# =============================================================================

oob_error <- tail(
  rf_model$err.rate[, "OOB"],
  1
)

# =============================================================================
# Permutation test
# =============================================================================
# To do: Refactor robustness ####

perm_acc <- NULL
perm_p <- NULL

if (permutation_test) {

  set.seed(seed)

  perm_acc <- numeric(nperm)

  for (i in seq_len(nperm)) {

    perm_y_train <- sample(y_train)

    perm_model <- randomForest::randomForest(
      x = X_train,
      y = perm_y_train,
      ntree = ntree,
      importance = FALSE
    )

    perm_pred <- predict(
      perm_model,
      newdata = X_test
    )

    perm_acc[i] <- mean(
      perm_pred == y_test
    )
  }

  perm_p <- mean(
    perm_acc >= accuracy
  )
}

# =============================================================================
# Plots
# =============================================================================

plots <- list()

if (plot) {

  gg <- ggplot2::ggplot

  # -----------------------------------------------------------------------
  # Confusion matrix
  # -----------------------------------------------------------------------

  cm_df <- as.data.frame(cm_tab)

  gg_cm <- gg(
    cm_df,
    ggplot2::aes(
      x = .data$Predicted,
      y = .data$Observed,
      fill = .data$Freq
    )
  ) +
    ggplot2::geom_tile() +
    ggplot2::geom_text(
      ggplot2::aes(label = .data$Freq),
      color = "white",
      size = 5
    ) +
    ggplot2::scale_fill_gradient(
      low = "lightblue",
      high = "steelblue",
      guide = "none"
    ) +
    ggplot2::labs(
      title = "Confusion Matrix",
      x = NULL,
      y = NULL
    ) +
    ggplot2::theme_bw(
      base_size = 12
    )

  # -----------------------------------------------------------------------
  # OOB error
  # -----------------------------------------------------------------------

  err_df <- data.frame(
    Tree = seq_along(
      rf_model$err.rate[, "OOB"]
    ),
    OOB = rf_model$err.rate[, "OOB"]
  )

  gg_oob <- gg(
    err_df,
    ggplot2::aes(
      x = .data$Tree,
      y = .data$OOB)
  ) +
    ggplot2::geom_line(
      linewidth = 1,
      colour = "firebrick"
    ) +
    ggplot2::theme_bw(
      base_size = 12
    ) +
    ggplot2::labs(
      title = "Out-of-Bag Error",
      x = "Trees",
      y = "OOB Error"
    )

  # -----------------------------------------------------------------------
  # Importance
  # -----------------------------------------------------------------------

  gg_imp <- gg(
    top_features,
    ggplot2::aes(
      x = stats::reorder(
        .data$Feature,
        .data[[importance_col]]
      ),
      y = .data[[importance_col]]
    )
  ) +
    ggplot2::geom_col(
      fill = "steelblue"
    ) +
    ggplot2::coord_flip() +
    ggplot2::theme_bw(
      base_size = 12
    ) +
    ggplot2::labs(
      title = "Variable Importance",
      x = NULL,
      y = importance_col
    )

  plots$confusion <- gg_cm
  plots$oob <- gg_oob
  plots$importance <- gg_imp

  # -----------------------------------------------------------------------
  # ROC
  # -----------------------------------------------------------------------

  if (!is.null(roc_obj)) {

    roc_df <- data.frame(
      TPR = rev(
        roc_obj$sensitivities
      ),
      FPR = rev(
        1 - roc_obj$specificities
      )
    )

    gg_roc <- gg(
      roc_df,
      ggplot2::aes(
        x = .data$FPR,
        y = .data$TPR)
    ) +
      ggplot2::geom_line(
        colour = "darkgreen",
        linewidth = 1.2
      ) +
      ggplot2::geom_abline(
        intercept = 0,
        slope = 1,
        linetype = 2
      ) +
      ggplot2::annotate(
        "text",
        x = 0.70,
        y = 0.15,
        label = paste0(
          "AUC = ",
          round(auc_val, 3)
        )
      ) +
      ggplot2::theme_bw(
        base_size = 12
      ) +
      ggplot2::labs(
        title = "ROC Curve",
        x = "1 - Specificity",
        y = "Sensitivity"
      )

    plots$roc <- gg_roc

    plots$combined <-
      (gg_cm | gg_oob) /
      (gg_roc | gg_imp)

  } else {

    plots$combined <-
      (gg_cm | gg_oob) /
      (gg_imp | patchwork::plot_spacer())
  }

  # -----------------------------------------------------------------------
  # Permutation plot
  # -----------------------------------------------------------------------

  if (
    permutation_test &&
    !is.null(perm_acc)
  ) {

    perm_df <- data.frame(
      Accuracy = perm_acc
    )

    gg_perm <- gg(
      perm_df,
      ggplot2::aes(
        x = .data$Accuracy)
    ) +
      ggplot2::geom_histogram(
        bins = 30,
        fill = "grey70",
        colour = "black"
      ) +
      ggplot2::geom_vline(
        xintercept = accuracy,
        colour = "red",
        linewidth = 1.2
      ) +
      ggplot2::theme_bw(
        base_size = 12
      ) +
      ggplot2::labs(
        title = "Permutation Test",
        subtitle = paste0(
          "p = ",
          round(perm_p, 4)
        ),
        x = "Permutation accuracy",
        y = "Count"
      )

    plots$permutation <- gg_perm
  }

  print(plots$combined)

  if (
    permutation_test &&
    !is.null(plots$permutation)
  ) {
    print(plots$permutation)
  }
}

# =============================================================================
# Output
# =============================================================================

obj <- list(

  call = match.call(),

  # Model
  model = rf_model,

  # Data
  x = X,
  y = y,

  x_train = X_train,
  x_test = X_test,

  y_train = y_train,
  y_test = y_test,

  train_samples = rownames(X_train),
  test_samples = rownames(X_test),

  features = colnames(X),

  # Predictions
  predictions = pred_class,
  probabilities = pred_prob,

  # Performance
  confusion_matrix = cm,
  metrics = metrics,

  # Importance
  importance = imp_df,
  top_features = top_features,

  # Diagnostics
  oob_error = oob_error,

  permutation =
    if (permutation_test) {
      list(
        acc = perm_acc,
        p_value = perm_p
      )
    } else {
      NULL
    },

  # Plots
  plots = plots,

  # Parameters
  parameters = list(
    target_var = target_var,
    feature_subset = feature_subset,
    sample_col = sample_col,
    train_fraction = train_fraction,
    ntree = ntree,
    seed = seed,
    positive_class = positive_class,
    permutation_test = permutation_test,
    nperm = nperm
  )
)

class(obj) <- "learn.rf"

print(obj)

return(invisible(obj))

}

# =============================================================================
# Print S3
# =============================================================================
#' Print method for learn.rf objects
#'
#' Displays a formatted summary of a \code{learn.rf} object.
#'
#' @param x An object of class \code{learn.rf}.
#' @param ... Further arguments (ignored).
#' @return Invisibly returns \code{x}.
#' @method print learn.rf
#' @export
print.learn.rf <- function(x, ...) {

  .print_header("Random Forest Results")

  n_train <- length(x$y_train)
  n_test  <- length(x$y_test)
  n_feat  <- length(x$features)

  classes <- paste(
    levels(x$y_test),
    collapse = " vs "
  )

  .print_block("Data & Setup", function() {

    cat("Target Variable:       ", x$parameters$target_var, "(", classes, ")\n")
    cat("Samples (Train/Test):  ", n_train, "/", n_test, "\n")
    cat("Features Used:         ", n_feat, "\n")
