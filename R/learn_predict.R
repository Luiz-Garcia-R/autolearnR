# =============================================================================
# LEARN PREDICT
# =============================================================================

#' Predict New Observations Using a Frozen Classification Model
#'
#' Applies a previously trained and frozen classification model to new
#' observations. Supports Logistic Regression, Elastic Net, Decision Trees,
#' Random Forest, and Support Vector Machines.
#'
#' The function generates class predictions and probability estimates using
#' the original model without retraining or modifying its parameters.
#' When true class labels are provided, predictive performance is evaluated
#' in the independent external dataset and compared with the performance
#' originally obtained in the model's reference test set.
#'
#' Performance evaluation includes accuracy, Kappa, macro-averaged precision,
#' recall and F1-score, as well as class-specific precision, recall,
#' specificity and F1-score. For binary classification, ROC curves and AUC
#' values are additionally calculated.
#'
#' Comparative performance is assessed using independent bootstrap
#' resampling for classification metrics and DeLong's method for AUC
#' comparison. Comparative visualizations include a confusion matrix,
#' ROC curve comparison, and a forest plot displaying differences in
#' predictive performance.
#'
#' @param frozen_model A validated frozen model generated by one of the
#'   supported \code{learn_*} classification functions. The model must contain
#'   the fitted classifier, predictor information, target class levels,
#'   and reference evaluation results.
#'
#' @param new_data A data frame containing the predictor variables required
#'   by the frozen model. Additional columns are ignored. All required
#'   predictors must be available and compatible with the original model.
#'
#' @param sample_col Optional character string specifying the column
#'   containing sample identifiers. If \code{NULL}, row names are used.
#'   Sample identifiers must be non-missing, non-empty, and unique.
#'   Defaults to \code{NULL}.
#'
#' @param true_labels Optional vector containing the observed class labels
#'   corresponding to the samples in \code{new_data}. If provided, external
#'   classification performance is evaluated and compared with the original
#'   reference test set. All labels must correspond to the target classes
#'   represented in the frozen model. Defaults to \code{NULL}.
#'
#' @param n_boot Integer specifying the number of bootstrap iterations used
#'   to estimate confidence intervals for classification metrics and their
#'   differences between the reference and external datasets. Defaults to
#'   \code{2000}. Only used when \code{true_labels} is provided.
#'
#' @param conf_level Numeric value specifying the confidence level used
#'   for confidence interval estimation. Defaults to \code{0.95}.
#'
#' @param seed Optional integer specifying the random seed used for
#'   reproducible bootstrap resampling. If \code{NULL}, the seed is derived
#'   from the reference model's bootstrap seed when available. Defaults
#'   to \code{NULL}.
#'
#' @param plot Logical value indicating whether evaluation plots should be
#'   generated and displayed. Defaults to \code{TRUE}. When \code{FALSE}\,
#'   numerical results are still calculated and returned, but no plots are
#'   generated. Plots are only generated when \code{true_labels} is provided.
#'
#' @return An object of class \code{learn_predict}, containing:
#' \describe{
#'   \item{call}{The original function call.}
#'   \item{algorithm}{Name of the classification algorithm used for prediction.}
#'   \item{model_family}{Classification type, such as binomial or
#'   multinomial.}
#'   \item{frozen_model}{The original frozen model used for prediction.}
#'   \item{features}{Character vector containing the predictor variables
#'   used by the model.}
#'   \item{sample_ids}{Character vector containing the identifiers of
#'   the predicted samples.}
#'   \item{n_samples}{Number of observations in the external dataset.}
#'   \item{prediction_data}{Data frame containing sample identifiers and
#'   predicted class labels.}
#'   \item{predictions}{Factor containing the predicted class labels.}
#'   \item{probabilities}{Matrix containing predicted class probabilities,
#'   with one column per target class.}
#'   \item{decision_values}{Matrix containing model decision values,
#'   when available. Otherwise, \code{NULL}.}
#'   \item{true_labels}{Observed class labels supplied through
#'   \code{true_labels}, or \code{NULL} when external evaluation was
#'   not performed.}
#'   \item{external_performance}{List containing external classification
#'   performance results, when observed labels are available:
#'     \describe{
#'       \item{confusion_matrix}{Classification confusion matrix.}
#'       \item{confusion_table}{Confusion table containing observed and
#'       predicted class counts.}
#'       \item{metrics}{Named vector containing classification performance
#'       metrics, including AUC for binary classification.}
#'       \item{confidence_intervals}{Data frame containing confidence
#'       intervals for classification metrics, estimated using bootstrap
#'       resampling, and DeLong's method for AUC.}
#'     }
#'   }
#'   \item{external_roc}{ROC analysis results for binary classification,
#'   including the ROC object, AUC estimate, confidence interval, and
#'   positive and negative class definitions. Otherwise, \code{NULL}.}
#'   \item{external_auc_ci}{List containing the lower confidence limit,
#'   AUC estimate, upper confidence limit, and estimation method for
#'   external AUC. Otherwise, \code{NULL}.}
#'   \item{comparison}{List containing comparative performance results,
#'   when observed labels are available:
#'     \describe{
#'       \item{metrics}{Comparison of reference and external classification
#'       metrics, including estimates, differences, confidence intervals,
#'       and bootstrap information.}
#'       \item{auc}{Comparison of reference and external AUC values using
#'       DeLong's method for independent ROC curves. Otherwise, \code{NULL}.}
#'       \item{summary}{Consolidated data frame containing reference and
#'       external estimates, their differences, confidence intervals, and
#'       associated methods.}
#'     }
#'   }
#'   \item{plots}{List containing external evaluation and comparative
#'   visualizations, when \code{plot = TRUE} and observed labels are available:
#'     \describe{
#'       \item{confusion}{Confusion matrix plot for the external dataset.}
#'       \item{roc}{Overlay of reference and external ROC curves for
#'       binary classification. Otherwise, \code{NULL}.}
#'       \item{combined}{Combined panel containing the confusion matrix
#'       and ROC comparison, when ROC analysis is available, or the
#'       confusion matrix alone for multiclass classification.}
#'       \item{forest}{Forest plot displaying differences in classification
#'       performance between the external and reference datasets.}
#'     }
#'   }
#' }
#'
#' @details
#' The function does not retrain, optimize, or modify the frozen model.
#' Predictions are generated using the original fitted classifier and
#' predictor configuration. The external dataset must contain all predictor
#' variables required by the model.
#'
#' When \code{true_labels = NULL}, the function performs prediction only.
#' In this case, classification performance, confidence intervals,
#' comparative statistics, and evaluation plots are not calculated.
#'
#' When observed labels are provided, the external dataset is evaluated
#' independently and compared with the original reference test set stored
#' in the frozen model. The reference dataset corresponds to the holdout
#' test samples used during the original model evaluation, whereas the
#' external dataset contains the newly supplied observations.
#'
#' Classification metrics are estimated independently for each dataset.
#' Confidence intervals for the differences between reference and external
#' metrics are obtained using non-parametric independent bootstrap
#' resampling. Samples are resampled with replacement within each dataset,
#' preserving their respective sample sizes.
#'
#' Differences are calculated as:
#'
#' \deqn{\Delta = \text{External} - \text{Reference}}
#'
#' Positive differences indicate higher external performance, whereas
#' negative differences indicate lower external performance. Confidence
#' intervals are estimated using the percentile method. At least 80\% of
#' bootstrap iterations must produce valid estimates for a confidence
#' interval to be reported.
#'
#' For binary classification, ROC curves and AUC values are calculated
#' using predicted class probabilities. AUC confidence intervals are
#' estimated using DeLong's method. Differences between reference and
#' external AUC values are evaluated using the DeLong test for independent
#' ROC curves. The confidence interval for the AUC difference is calculated
#' using the independent DeLong variance estimates.
#'
#' The forest plot displays the difference between external and reference
#' performance estimates, together with their corresponding confidence
#' intervals. The vertical reference line at zero indicates no observed
#' difference between datasets.
#'
#' Comparative results should be interpreted in the context of the
#' independent datasets being evaluated. Differences in sample size,
#' class distribution, population characteristics, and data acquisition
#' procedures may influence external performance estimates.
#' In particular, the absence of a statistically detectable difference
#' does not establish equivalence between datasets or guarantee model
#' generalizability to other populations.
#'
#' @examples
#' # Example: Apply a frozen classification model to an independent dataset.
#'
#' # Prepare the iris dataset
#' iris_data <- iris[
#'   iris$Species %in% c("versicolor", "virginica"),
#' ]
#'
#' iris_data$Sample <- rownames(iris_data)
#' iris_data$Species <- droplevels(iris_data$Species)
#'
#' # Split the data into training and external evaluation datasets
#' set.seed(123)
#' train_ids <- sample(
#'   seq_len(nrow(iris_data)),
#'   size = floor(0.7 * nrow(iris_data))
#' )
#'
#' train_data <- iris_data[train_ids, ]
#' external_data <- iris_data[-train_ids, ]
#'
#' # Train a classification model (e.g. 'learn_tree()')
#' model <- learn_tree(
#'   data = train_data,
#'   target_var = "Species",
#'   feature_subset = c(
#'     "Sepal.Length",
#'     "Sepal.Width",
#'     "Petal.Length",
#'     "Petal.Width"
#'   ),
#'   sample_col = "Sample",
#'   train_fraction = 0.7,
#'   seed = 123,
#'   plot = FALSE
#' )
#'
#' # Freeze the trained model
#' frozen <- model$frozen_model
#'
#' # Generate predictions and evaluate external performance
#' prediction <- learn_predict(
#'   frozen_model = frozen,
#'   new_data = external_data,
#'   sample_col = "Sample",
#'   true_labels = external_data$Species,
#'   n_boot = 2000,
#'   conf_level = 0.95,
#'   seed = 456,
#'   plot = TRUE
#' )
#'
#' # Inspect external performance
#' prediction$external_performance$metrics
#'
#' # Inspect reference versus external comparison
#' prediction$comparison$summary
#'
#' @references
#' Sokolova, M., & Lapalme, G. (2009).
#' A systematic analysis of performance measures for classification tasks.
#' \emph{Information Processing & Management}, 45(4), 427-437.
#' https://doi.org/10.1016/j.ipm.2009.03.002
#'
#' DeLong, E. R., DeLong, D. M., & Clarke-Pearson, D. L. (1988).
#' Comparing the areas under two or more correlated receiver operating
#' characteristic curves: A nonparametric approach.
#' \emph{Biometrics}, 44(3), 837-845.
#' https://doi.org/10.2307/2531595
#'
#' @seealso
#' \code{\link{learn_compare}},
#' \code{\link{learn_tree}},
#' \code{\link{learn_logistic}},
#' \code{\link{learn_elastic_net}},
#' \code{\link{learn_random_forest}},
#' \code{\link{learn_svm}}
#'
#' @export

learn_predict <- function(
    frozen_model,
    new_data,
    sample_col = NULL,
    true_labels = NULL,
    n_boot = 2000,
    conf_level = 0.95,
    seed = NULL,
    plot = TRUE
) {

# =============================================================================
# 1. Validate frozen model
# =============================================================================

.validate_frozen_model(frozen_model)

# =============================================================================
# 2. Validate new data structure
# =============================================================================

if (!is.data.frame(new_data)) {
  stop("'new_data' must be a data.frame.")
}

if (nrow(new_data) == 0) {
  stop("'new_data' must contain at least one observation.")
}

# Validate plot
if (
  !is.logical(plot) ||
  length(plot) != 1 ||
  is.na(plot)
) {
  stop("'plot' must be TRUE or FALSE.")
}

# =============================================================================
# 3. Extract sample identifiers
# =============================================================================

if (!is.null(sample_col)) {

  if (
    !is.character(sample_col) ||
    length(sample_col) != 1 ||
    is.na(sample_col) ||
    !sample_col %in% colnames(new_data)
  ) {
    stop(
      "'sample_col' must specify an existing column in 'new_data'."
    )
  }

  if (sample_col %in% frozen_model$predictor_names) {
    stop(
      "'sample_col' cannot be one of the model predictors."
    )
  }

  sample_ids <- as.character(new_data[[sample_col]])

} else {

  sample_ids <- rownames(new_data)

}

if (
  length(sample_ids) != nrow(new_data) ||
  anyNA(sample_ids) ||
  any(!nzchar(sample_ids)) ||
  anyDuplicated(sample_ids)
) {
  stop(
    "Sample identifiers must be non-missing, non-empty and unique."
  )
}

# =============================================================================
# 4. Identify algorithm
# =============================================================================

algorithm <- frozen_model$algorithm

# =============================================================================
# 5. Generate predictions
# =============================================================================

prediction_result <- switch(

  algorithm,

  logistic = .predict_logistic(
    new_data = new_data,
    frozen_model = frozen_model
  ),

  elastic_net = .predict_elastic(
    new_data = new_data,
    frozen_model = frozen_model
  ),

  tree = .predict_tree(
    new_data = new_data,
    frozen_model = frozen_model
  ),

  random_forest = .predict_rf(
    new_data = new_data,
    frozen_model = frozen_model
  ),

  svm = .predict_svm(
    new_data = new_data,
    frozen_model = frozen_model
  )

)

# =============================================================================
# 6. Validate prediction output
# =============================================================================

required_outputs <- c(
  "predictions",
  "probabilities",
  "decision_values"
)

if (
  !is.list(prediction_result) ||
  !all(required_outputs %in% names(prediction_result))
) {
  stop(
    "Prediction helper returned an invalid output structure."
  )
}

predictions <- prediction_result$predictions
probabilities <- prediction_result$probabilities
decision_values <- prediction_result$decision_values

target_levels <- frozen_model$response$target_levels

if (
  !is.factor(predictions) ||
  length(predictions) != nrow(new_data) ||
  !identical(levels(predictions), target_levels) ||
  anyNA(predictions)
) {
  stop("Invalid predicted class labels returned by prediction helper.")
}

if (
  !is.matrix(probabilities) ||
  nrow(probabilities) != nrow(new_data) ||
  ncol(probabilities) != length(target_levels) ||
  !identical(colnames(probabilities), target_levels) ||
  any(!is.finite(probabilities)) ||
  any(probabilities < 0 | probabilities > 1)
) {
  stop("Invalid predicted probabilities returned by prediction helper.")
}

if (
  any(abs(rowSums(probabilities) - 1) > 1e-6)
) {
  stop(
    "Predicted probabilities do not sum to 1 for all observations."
  )
}

if (
  !is.null(decision_values) &&
  (
    !is.matrix(decision_values) ||
    nrow(decision_values) != nrow(new_data) ||
    any(!is.finite(decision_values))
  )
) {
  stop("Invalid decision values returned by prediction helper.")
}

# Assign sample identifiers consistently
names(predictions) <- sample_ids
rownames(probabilities) <- sample_ids

if (!is.null(decision_values)) {
  rownames(decision_values) <- sample_ids
}

# =============================================================================
# 7. Validate true labels
# =============================================================================

if (!is.null(true_labels)) {

  if (
    !is.atomic(true_labels) ||
    is.matrix(true_labels) ||
    length(true_labels) != nrow(new_data) ||
    anyNA(true_labels)
  ) {
    stop(
      "'true_labels' must be a non-missing vector with one value per sample."
    )
  }

  true_labels <- factor(
    as.character(true_labels),
    levels = target_levels
  )

  if (anyNA(true_labels)) {
    stop(
      "'true_labels' contains classes not represented in the frozen model."
    )
  }

  names(true_labels) <- sample_ids

  # Validate n_boot
  if (
    length(n_boot) != 1 ||
    is.na(n_boot) ||
    n_boot < 1 ||
    n_boot != as.integer(n_boot)
  ) {
    stop("'n_boot' must be a positive integer when evaluating true labels.")
  }

}

# =============================================================================
# 8. External performance evaluation
# =============================================================================

external_performance <- NULL
external_roc <- NULL
external_auc_ci <- NULL

comparison <- NULL

if (!is.null(true_labels)) {

  # Determine reproducibility seeds
  reference_seed <- frozen_model$reference$
    evaluation_parameters$bootstrap_seed

  external_seed <- if (!is.null(seed)) {
    seed
  } else if (!is.null(reference_seed)) {
    reference_seed + 1
  } else {
    NULL
  }

  comparison_seed <- if (!is.null(external_seed)) {
    external_seed + 1
  } else {
    NULL
  }

  # ===============================================
  # 8.1. External classification metrics
  # ===============================================

  external_performance <- .classification_metrics(
    predicted = predictions,
    observed = true_labels,
    n_boot = n_boot,
    conf_level = conf_level,
    seed = external_seed
  )

  external_metrics <- external_performance$metrics

  external_confidence_intervals <-
    external_performance$confidence_intervals

  external_auc <- NA_real_

  # ===============================================
  # 8.2. External ROC and AUC
  # ===============================================

  if (frozen_model$model_family == "binomial") {

    positive_class <- frozen_model$reference$roc$levels[2]

    external_roc <- .classification_roc(
      observed = true_labels,
      probabilities = probabilities,
      positive_class = positive_class,
      conf_level = conf_level
    )

    external_auc <- external_roc$auc

    auc_ci_raw <- external_roc$auc_ci

    external_auc_ci <- list(
      lower = unname(auc_ci_raw[1]),
      estimate = unname(auc_ci_raw[2]),
      upper = unname(auc_ci_raw[3]),
      method = "delong"
    )

    auc_ci_row <- data.frame(
      Metric = "auc",
      Class = NA_character_,
      Estimate = external_auc_ci$estimate,
      Lower = external_auc_ci$lower,
      Upper = external_auc_ci$upper,
      N_valid = NA_integer_,
      N_boot = NA_integer_,
      Method = "delong"
    )

    external_confidence_intervals <- rbind(
      external_confidence_intervals,
      auc_ci_row
    )

  }

  external_metrics$auc <- external_auc

  # ===============================================
  # 8.3. Compare classification metrics
  # ===============================================

  comparison_metrics <- .compare_classification_performance(
    reference_observed = frozen_model$reference$observed,
    reference_predictions = frozen_model$reference$predictions,
    external_observed = true_labels,
    external_predictions = predictions,
    n_boot = n_boot,
    conf_level = conf_level,
    seed = comparison_seed
  )

  # ===============================================
  # 8.4. ompare AUC
  # ===============================================

  auc_comparison <- NULL

  if (frozen_model$model_family == "binomial") {

    auc_comparison <- .compare_auc(
      reference_roc = frozen_model$reference$roc,
      external_roc = external_roc$roc,
      conf_level = conf_level
    )

  }

  # ===============================================
  # 8.5. Combine comparison results
  # ===============================================

  comparison <- list(
    metrics = comparison_metrics,
    auc = auc_comparison
  )

}

# =============================================================================
# 9. Build comparison summary and plots
# =============================================================================

plot_list <- list(
  confusion = NULL,
  roc = NULL,
  combined = NULL,
  forest = NULL
)

if (!is.null(true_labels)) {

  # ===============================================
  # 9.1. Consolidated comparison summary
  # ===============================================

  comparison$summary <- .build_predict_comparison_summary(
    metrics_comparison = comparison$metrics,
    auc_comparison = comparison$auc
  )

  if (plot) {

    # ===============================================
    # 9.2. Confusion matrix
    # ===============================================

    plot_list$confusion <- .plot_confusion_matrix(
      confusion_table = external_performance$confusion_table
    )

    # ===============================================
    # 9.3. ROC comparison
    # ===============================================

    if (frozen_model$model_family == "binomial") {

      plot_list$roc <- .plot_predict_roc(
        reference_roc = frozen_model$reference$roc,
        external_roc = external_roc$roc
      )

    }

    # ===============================================
    # 9.4. Combined classification plots
    # ===============================================

    plot_list$combined <- .combine_classification_plots(
      plots = list(
        plot_list$confusion,
        plot_list$roc
      ),
      ncol = 2
    )

    # ===============================================
    # 9.5. Forest plot
    # ===============================================

    plot_list$forest <- .plot_predict_forest(
      comparison_summary = comparison$summary
    )

  }

}

# =============================================================================
# 10. Build prediction data
# =============================================================================

prediction_data <- data.frame(
  Sample = sample_ids,
  Predicted = predictions,
  stringsAsFactors = FALSE
)

# =============================================================================
# 11. Build output object
# =============================================================================

obj <- list(

  # Identification
  call = match.call(),
  algorithm = algorithm,
  model_family = frozen_model$model_family,

  # Model information
  frozen_model = frozen_model,

  # Data information
  features = frozen_model$predictor_names,
  sample_ids = sample_ids,
  n_samples = nrow(new_data),

  # Predictions
  prediction_data = prediction_data,
  predictions = predictions,
  probabilities = probabilities,
  decision_values = decision_values,

  # Evaluation
  true_labels = true_labels,
  external_performance = external_performance,
  external_roc = external_roc,
  external_auc_ci = external_auc_ci,

  # Statistical comparison
  comparison = comparison,

  # Plots
  plots = plot_list

)

class(obj) <- "learn_predict"

# =============================================================================
# 12. Output
# =============================================================================

print(obj)

# Display plots
if (plot) {

  if (!is.null(obj$plots$forest)) {
    print(obj$plots$forest)
  }

  if (!is.null(obj$plots$combined)) {
    print(obj$plots$combined)
  }

}

return(invisible(obj))

}

# =============================================================================
# PRINT S3
# =============================================================================
#' Print method for learn_predict objects
#'
#' Displays a summary of predictions generated by a frozen model.
#'
#' @param x An object of class \code{learn_predict}.
#' @param ... Further arguments (ignored).
#' @return Invisibly returns \code{x}.
#' @method print learn_predict
#' @export

print.learn_predict <- function(x, ...) {

algorithm_labels <- c(
  logistic = "Logistic Regression",
  elastic_net = "Elastic Net",
  tree = "Decision Tree",
  random_forest = "Random Forest",
  svm = "Support Vector Machine"
)

algorithm_label <- unname(
  algorithm_labels[x$algorithm]
)

.print_header("Prediction Results")

# ===============================================
# General information
# ===============================================

.print_block("Model & Data", function() {

  cat(
    "Algorithm:             ",
    algorithm_label,
    "\n"
  )

  cat(
    "Model Family:          ",
    x$model_family,
    "\n"
  )

  cat(
    "Samples Predicted:     ",
    x$n_samples,
    "\n"
  )

  cat(
    "Features Used:         ",
    length(x$features),
    "\n"
  )

  cat(
    "Decision Values:       ",
    if (is.null(x$decision_values)) {
      "Not available"
    } else {
      "Available"
    },
    "\n"
  )

})

# ===============================================
# Predicted class distribution
# ===============================================

.print_block("Predicted Class Distribution", function() {

  class_counts <- table(
    factor(
      x$predictions,
      levels = x$frozen_model$response$target_levels
    )
  )

  for (class_name in names(class_counts)) {

    cat(
      sprintf(
        "%-22s %d (%.1f%%)\n",
        paste0(class_name, ":"),
        class_counts[[class_name]],
        100 * class_counts[[class_name]] / x$n_samples
      )
    )

  }

})

invisible(x)

}
